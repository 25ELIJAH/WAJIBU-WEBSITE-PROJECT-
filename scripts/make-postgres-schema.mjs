// Generates the PostgreSQL flavour of the Prisma schema and its migration from prisma/schema.prisma
// (the SQLite schema used for local development). Re-run after every change to prisma/schema.prisma:
//
//   npm run db:postgres
//
// Output (commit it): prisma/postgres/schema.prisma and prisma/postgres/migrations/*
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const root = process.cwd();
const src = fs.readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");
if (!/provider\s*=\s*"sqlite"/.test(src)) throw new Error('prisma/schema.prisma must use provider = "sqlite" (dev).');

const outDir = path.join(root, "prisma", "postgres");
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(path.join(outDir, "migrations", "0001_init"), { recursive: true });

const pg = src
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"')
  .replace(/\/\/ SQLite keeps local development[\s\S]*?\n\ngenerator/, "// PostgreSQL flavour – GENERATED by `npm run db:postgres` from ../schema.prisma. Do not edit by hand.\n\ngenerator");
fs.writeFileSync(path.join(outDir, "schema.prisma"), pg);

const sql = execSync(
  "npx prisma migrate diff --from-empty --to-schema-datamodel prisma/postgres/schema.prisma --script",
  { cwd: root, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 }
);
fs.writeFileSync(path.join(outDir, "migrations", "0001_init", "migration.sql"), sql);
fs.writeFileSync(path.join(outDir, "migrations", "migration_lock.toml"), '# Please do not edit this file manually\nprovider = "postgresql"\n');
console.log("Postgres schema + migration written to prisma/postgres/");
